"""Storage ports. Every method takes fde_id, and implementations filter every query by it."""

from __future__ import annotations

from datetime import date, datetime
from typing import Any, Protocol

from fde_core.domain.action_points import ActionItemRecord, SyncSummary
from fde_core.domain.collection import SourceSnapshot
from fde_core.domain.daily_log import DailyLog, Usage
from fde_core.domain.events import ActivityEvent
from fde_core.domain.learnings import Learning
from fde_core.domain.review import DayOverrides
from fde_core.domain.review_request import ReviewRequest
from fde_core.domain.run import DayResult, RunPlan


class FdeProfileRepository(Protocol):
    def get(self, fde_id: str) -> dict[str, Any] | None: ...
    def find_fde_id_by_email(self, email: str) -> str | None: ...


class EventRepository(Protocol):
    def replace_day(self, fde_id: str, day: date, events: list[ActivityEvent]) -> int:
        """Upsert the day's events and delete the day's events not in the list. Returns deleted count."""
        ...

    def list_day(self, fde_id: str, day: date) -> list[ActivityEvent]: ...


class CollectedEventRepository(Protocol):
    """What each source returned for a day (redacted, before matching), with a snapshot of how it went."""

    def snapshots(self, fde_id: str, day: date) -> dict[str, SourceSnapshot]: ...
    def load(self, fde_id: str, day: date, source: str) -> list[ActivityEvent]: ...
    def save(self, snapshot: SourceSnapshot, events: list[ActivityEvent]) -> None:
        """Replace that source's stored events for the day, and its snapshot."""
        ...


class DailyLogRepository(Protocol):
    def save(self, log: DailyLog, expected_version: int | None = None) -> str:
        """Bumps `log.version`. With `expected_version`, raises when the stored log has another version."""
        ...

    def get(self, fde_id: str, day: date) -> DailyLog | None: ...
    def set_usage(self, fde_id: str, day: date, usage: Usage) -> None: ...


class DayOverridesRepository(Protocol):
    def get(self, fde_id: str, day: date) -> DayOverrides | None: ...
    def save(self, overrides: DayOverrides) -> None: ...


class RunRepository(Protocol):
    def start(self, plan: RunPlan, inputs: dict[str, str]) -> None: ...
    def record_result(self, run_id: str, fde_id: str, result: DayResult) -> None: ...
    def finish(self, run_id: str, fde_id: str, status: str, usage: Usage) -> None: ...
    def fail(self, run_id: str, fde_id: str, error: str) -> None: ...
    def record_action_points(self, run_id: str, fde_id: str, summary: SyncSummary) -> None: ...


class ReviewRequestRepository(Protocol):
    def create(self, request: ReviewRequest) -> None: ...
    def next_round(self, fde_id: str, day: date) -> int: ...
    def get(self, fde_id: str, request_id: str) -> ReviewRequest | None: ...
    def waiting_for_run(self, run_id: str) -> ReviewRequest | None: ...
    def mark_answered(self, request_id: str, source: str) -> bool: ...


class LearningRepository(Protocol):
    """The FDE's learnings; a run reads only the approved ones."""

    def approved(self, fde_id: str) -> list[Learning]: ...


class ActionItemRepository(Protocol):
    """Tasks already created in the tracker, by action point key."""

    def known_keys(self, fde_id: str, keys: list[str]) -> set[str]: ...
    def list_day(self, fde_id: str, day: date) -> list[ActionItemRecord]: ...
    def link_follow_ups(self, fde_id: str, key: str, follow_up_ids: list[str]) -> None: ...
    def record(self, item: ActionItemRecord) -> None: ...


class ReferenceCacheRepository(Protocol):
    def get(self, fde_id: str, kind: str) -> tuple[Any, datetime] | None:
        """Cached data and when it was fetched."""
        ...

    def put(self, fde_id: str, kind: str, data: Any) -> None: ...
